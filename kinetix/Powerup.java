package kinetix;

/**
 * The collectable powerups that sometimes fall from destroyed bricks. The
 * numbers correspond to the sprite filenames, e.g. barrel06 is the extend bat
 * powerup, frame 6.
 */
public enum Powerup {
  EXTEND_BAT,
  GUN,
  SMALL_BAT,
  MAGNET,
  MULTI_BALL,
  FAST_BALLS,
  SLOW_BALLS,
  PORTAL,
  EXTRA_LIFE
}
